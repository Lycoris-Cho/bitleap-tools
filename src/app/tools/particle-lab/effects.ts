/**
 * 生成可直接运行（也能直接双击打开）的单文件 HTML。
 */
export function buildEffectHtml(id: string, options?: Partial<EffectOptions>): string {
  const def = EFFECTS.find((item) => item.id === id)
  if (!def) throw new Error("未知特效：" + id)

  const opt: EffectOptions = { ...DEFAULT_OPTIONS, ...def.defaults, ...options }

  const runtime = [
    "(function () {",
    '  "use strict";',
    "  var PALETTES = " + JSON.stringify(PALETTES) + ";",
    "  var FX = {",
    '    canvas: document.getElementById("fx"),',
    "    ctx: null,",
    "    W: 1, H: 1, dpr: 1,",
    "    t: 0, dt: 0.016, frames: 0, paused: false,",
    "    opt: " + JSON.stringify(opt) + ",",
    "    pointer: { x: -9999, y: -9999, has: false, down: false }",
    "  };",
    "  window.FX = FX;",
    "  /* 出问题时不静默：着色器编译失败之类的错误都记在这里，便于排查 */",
    "  FX.errors = [];",
    "  window.addEventListener(\"error\", function (e) {",
    "    FX.errors.push(String((e && (e.message || e.error)) || e));",
    "  });",
    "",
    "  /* ---------- 配色 ---------- */",
    "  function hexToRgb(h) {",
    "    var v = parseInt(h.slice(1), 16);",
    "    return [(v >> 16) & 255, (v >> 8) & 255, v & 255];",
    "  }",
    "  FX.bgHex = \"#000000\";",
    "  FX.bgRGB = [0, 0, 0];",
    "  FX.colorsHex = [];",
    "  FX.colorsRGB = [];",
    "  FX.fade = function (a) {",
    '    return "rgba(" + FX.bgRGB[0] + "," + FX.bgRGB[1] + "," + FX.bgRGB[2] + "," + a + ")";',
    "  };",
    "  /* FX.color(i, a) 取配色里第 i 个颜色，a 省略时为不透明 */",
    "  FX.color = function (i, a) {",
    "    var c = FX.colorsRGB[((i % FX.colorsRGB.length) + FX.colorsRGB.length) % FX.colorsRGB.length];",
    '    return a === undefined ? "rgb(" + c[0] + "," + c[1] + "," + c[2] + ")" : "rgba(" + c[0] + "," + c[1] + "," + c[2] + "," + a + ")";',
    "  };",
    "  function applyPalette() {",
    "    var p = PALETTES[FX.opt.palette] || PALETTES[0];",
    "    FX.bgHex = p.bg;",
    "    FX.bgRGB = hexToRgb(p.bg);",
    "    FX.colorsHex = p.colors.slice();",
    "    FX.colorsRGB = p.colors.map(function (c) { return hexToRgb(c); });",
    "    document.body.style.background = p.bg;",
    "  }",
    "  applyPalette();",
    "",
    "  /* ---------- 值噪声：给效果做平滑游走用 ---------- */",
    "  function ihash(x, y) {",
    "    var n = (x * 374761393 + y * 668265263) | 0;",
    "    n = (n ^ (n >> 13)) | 0;",
    "    n = (n * 1274126177) | 0;",
    "    return ((n ^ (n >> 16)) >>> 0) / 4294967296;",
    "  }",
    "  FX.noise2 = function (x, y) {",
    "    var xi = Math.floor(x), yi = Math.floor(y);",
    "    var xf = x - xi, yf = y - yi;",
    "    var u = xf * xf * (3 - 2 * xf), v = yf * yf * (3 - 2 * yf);",
    "    var a = ihash(xi, yi), b = ihash(xi + 1, yi), c = ihash(xi, yi + 1), d = ihash(xi + 1, yi + 1);",
    "    return (a + (b - a) * u) * (1 - v) + (c + (d - c) * u) * v;",
    "  };",
    "",
    "  /* ---------- 尺寸与指针 ---------- */",
    "  FX.dpr = Math.min(window.devicePixelRatio || 1, 2);",
    "  function resize() {",
    "    var w = FX.canvas.clientWidth || window.innerWidth || 1;",
    "    var h = FX.canvas.clientHeight || window.innerHeight || 1;",
    "    FX.W = w;",
    "    FX.H = h;",
    "    /* 缩放系数：面板预览与全屏尺寸差别很大，粒子类效果按这两个值适配 */",
    "    FX.scale = Math.max(0.35, Math.min(2.2, Math.min(w, h) / 900));",
    "    FX.k = Math.max(0.5, Math.min(2.4, (w * h) / 900000));",
    "    var pw = Math.max(1, Math.round(w * FX.dpr));",
    "    var ph = Math.max(1, Math.round(h * FX.dpr));",
    "    if (FX.canvas.width !== pw || FX.canvas.height !== ph) {",
    "      FX.canvas.width = pw;",
    "      FX.canvas.height = ph;",
    "    }",
    "    if (FX.ctx && FX.ctx.setTransform) FX.ctx.setTransform(FX.dpr, 0, 0, FX.dpr, 0, 0);",
    "  }",
    "  /* WebGL 里 y 轴朝上，取归一化坐标用这两个 */",
    "  FX.nx = function () { return FX.pointer.x / Math.max(1, FX.W); };",
    "  FX.ny = function () { return 1 - FX.pointer.y / Math.max(1, FX.H); };",
    "",
    "  window.addEventListener(\"pointermove\", function (e) {",
    "    FX.pointer.x = e.clientX;",
    "    FX.pointer.y = e.clientY;",
    "    FX.pointer.has = true;",
    "  }, { passive: true });",
    "  window.addEventListener(\"pointerdown\", function (e) {",
    "    FX.pointer.down = true;",
    "    FX.pointer.x = e.clientX;",
    "    FX.pointer.y = e.clientY;",
    "    FX.pointer.has = true;",
    "  }, { passive: true });",
    "  window.addEventListener(\"pointerup\", function () { FX.pointer.down = false; }, { passive: true });",
    "  window.addEventListener(\"pointerleave\", function () {",
    "    FX.pointer.has = false;",
    "    FX.pointer.x = -9999;",
    "    FX.pointer.y = -9999;",
    "  });",
    "",
    "  /* ---------- 生命周期 ---------- */",
    "  function setup() {",
    "    resize();",
    "    if (typeof fxSetup === \"function\") fxSetup();",
    "  }",
    "",
    "  var reduce = window.matchMedia(\"(prefers-reduced-motion: reduce)\").matches;",
    "  var freezeAfter = reduce ? 90 : 0;",
    "  var last = 0;",
    "",
    "  function loop(now) {",
    "    var tn = now * 0.001;",
    "    var dt = last ? Math.min(0.05, tn - last) : 0.016;",
    "    last = tn;",
    "    if (!FX.paused) {",
    "      FX.dt = dt;",
    "      FX.t += dt;",
    "      FX.frames += 1;",
    "      if (typeof fxFrame === \"function\") fxFrame(FX.t);",
    "      if (freezeAfter && FX.frames >= freezeAfter) FX.paused = true;",
    "    }",
    "    requestAnimationFrame(loop);",
    "  }",
    "",
    "  window.addEventListener(\"message\", function (e) {",
    "    var d = e.data;",
    "    if (!d || typeof d !== \"object\") return;",
    "    if (d.type === \"fx:pause\") FX.paused = true;",
    "    else if (d.type === \"fx:resume\") { FX.paused = false; FX.frames = 0; }",
    "    else if (d.type === \"fx:options\" && d.options) {",
    "      var reset = false;",
    "      if (typeof d.options.speed === \"number\") FX.opt.speed = d.options.speed;",
    "      if (typeof d.options.density === \"number\" && d.options.density !== FX.opt.density) {",
    "        FX.opt.density = d.options.density;",
    "        reset = true;",
    "      }",
    "      if (typeof d.options.palette === \"number\" && d.options.palette !== FX.opt.palette) {",
    "        FX.opt.palette = d.options.palette;",
    "        applyPalette();",
    "      }",
    "      /* 帧里实时读颜色，所以换配色通常不用重建；重建过的资源交给 fxPalette 处理 */",
    "      if (reset) setup();",
    "      else if (typeof fxPalette === \"function\") fxPalette();",
    "    }",
    "  });",
    "",
    "  var resizeTimer = 0;",
    "  window.addEventListener(\"resize\", function () {",
    "    clearTimeout(resizeTimer);",
    "    resizeTimer = setTimeout(setup, 140);",
    "  });",
    "",
    "  /* ================= 效果实现 ================= */",
    "",
    def.script,
    "",
    "  /* ================= 启动 ================= */",
    "  setup();",
    "  /* 先同步画一帧，避免首帧空白 */",
    "  FX.frames = 1;",
    "  if (typeof fxFrame === \"function\") fxFrame(0);",
    "  requestAnimationFrame(loop);",
    "})();",
  ].join("\n")

  return [
    "<!doctype html>",
    '<html lang="zh-CN">',
    "<head>",
    '<meta charset="utf-8" />',
    '<meta name="viewport" content="width=device-width, initial-scale=1" />',
    '<meta name="theme-color" content="' + (PALETTES[opt.palette] || PALETTES[0]).bg + '" />',
    "<title>" + def.name + " · BitLeap 特效</title>",
    "<style>",
    BASE_CSS,
    "</style>",
    "</head>",
    "<body>",
    '<canvas id="fx"></canvas>',
    "<script>",
    runtime,
    "</scr" + "ipt>",
    "</body>",
    "</html>",
    "",
  ].join("\n")
}

