/**
 * 粒子与背景特效库 · 效果定义
 *
 * 设计要点：每个效果的“唯一真源”是一段能独立运行的 HTML 文件，
 * 页面里的预览用 iframe(srcdoc) 加载的正是同一份 HTML，
 * 所以「预览看到的」与「下载得到的」保证逐字一致，不存在两套实现走偏的问题。
 *
 * 效果代码运行在共享外壳里，外壳负责：画布尺寸与 DPR、帧循环、帧间隔 dt、
 * 暂停/恢复、配色解析、值噪声、指针坐标。效果只需要实现两个函数：
 *
 *   fxSetup()      初始化（挂载时、尺寸变化时、密度变化时会被调用，必须可重复执行）
 *   fxFrame(t)     每帧绘制，t 为累计运行秒数（暂停时不推进）
 *   fxPalette()    可选。配色变化时调用，用于重建缓存了颜色的资源（如精灵图）
 *
 * 效果代码里不要出现反引号和 ${ }（整份 HTML 由模板字符串拼装）。
 */

export type EffectCategory = "particle" | "background"

export type EffectOptions = {
  /** 速度倍率 */
  speed: number
  /** 密度倍率 */
  density: number
  /** 配色索引 */
  palette: number
}

export type ControlKey = keyof EffectOptions

export type EffectDef = {
  id: string
  name: string
  desc: string
  category: EffectCategory
  tags: string[]
  /** 该效果真正会用到的调节项，UI 只渲染这些 */
  controls: ControlKey[]
  defaults: Partial<EffectOptions>
  script: string
}

export const DEFAULT_OPTIONS: EffectOptions = { speed: 1, density: 1, palette: 0 }

